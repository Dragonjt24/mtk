package com.gaminggear.web;

import com.gaminggear.config.AppConfig;
import com.gaminggear.config.DependencyContainer;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;

import static org.junit.jupiter.api.Assertions.*;

class JavaApiBridgeServerTest {

    private JavaApiBridgeServer bridgeServer;
    private int port;
    private final HttpClient client = HttpClient.newHttpClient();

    @BeforeEach
    void setUp() throws Exception {
        AppConfig cfg = new AppConfig();
        cfg.setAutoSaveEnabled(false);
        DependencyContainer container = new DependencyContainer(cfg, false);
        bridgeServer = new JavaApiBridgeServer(container);
        port = 18085;
        bridgeServer.start(port);
    }

    @AfterEach
    void tearDown() {
        if (bridgeServer != null) {
            bridgeServer.stop();
        }
    }

    @Test
    void healthAndLoginAndPricingAndPaymentFlow_workThroughJavaHttpBridge() throws Exception {
        HttpResponse<String> health = client.send(
                HttpRequest.newBuilder(URI.create("http://127.0.0.1:" + port + "/api/java/health")).GET().build(),
                HttpResponse.BodyHandlers.ofString()
        );
        assertEquals(200, health.statusCode());
        assertTrue(health.body().contains("Java 17"));

        // Login with admin
        HttpResponse<String> login = client.send(
                HttpRequest.newBuilder(URI.create("http://127.0.0.1:" + port + "/api/java/auth/login"))
                        .header("Content-Type", "application/json")
                        .POST(HttpRequest.BodyPublishers.ofString("{\"username\":\"admin\",\"password\":\"admin123\"}"))
                        .build(),
                HttpResponse.BodyHandlers.ofString()
        );
        assertEquals(200, login.statusCode());
        assertTrue(login.body().contains("ADMIN"));

        // Preview pricing via Factory + Strategy
        HttpResponse<String> pricing = client.send(
                HttpRequest.newBuilder(URI.create("http://127.0.0.1:" + port + "/api/java/orders/preview-pricing"))
                        .header("Content-Type", "application/json")
                        .POST(HttpRequest.BodyPublishers.ofString("{\"originalTotal\":1000000,\"discountType\":\"VIP\"}"))
                        .build(),
                HttpResponse.BodyHandlers.ofString()
        );
        assertEquals(200, pricing.statusCode());
        assertTrue(pricing.body().contains("150000"));
        assertTrue(pricing.body().contains("850000"));

        // Download real PDF generated by OpenPDF
        HttpResponse<byte[]> pdf = client.send(
                HttpRequest.newBuilder(URI.create("http://127.0.0.1:" + port + "/api/java/bills/BILL-1001/pdf")).GET().build(),
                HttpResponse.BodyHandlers.ofByteArray()
        );
        assertEquals(200, pdf.statusCode());
        assertTrue(pdf.body().length > 500);
        assertEquals("%PDF", new String(pdf.body(), 0, 4));
    }
}
